/**
 * Название города в предложном падеже: «Москва» → «в Москве».
 *
 * Правила приблизительные и покрывают массовые случаи — этого достаточно:
 * заголовок с «отзывы о квартирах в Москве» отвечает реальному запросу, а
 * «в Москва» просто выглядит браком. Точное склонение всех топонимов
 * потребовало бы словаря, а он нужен ради единиц исключений.
 *
 * Такая же функция есть на бэкенде (back/src/seo/city-case.ts): заголовки
 * страниц он собирает сам, и формы обязаны совпадать.
 */
export function cityIn(cityName: string): string {
  const name = cityName.trim()
  if (!name) return name

  const lower = name.toLowerCase()

  // Феодосия → Феодосии, Австрия → Австрии
  if (lower.endsWith('ия')) return `${name.slice(0, -1)}и`
  // Москва → Москве, Балашиха → Балашихе
  if (lower.endsWith('а')) return `${name.slice(0, -1)}е`
  // Казань → Казани, Тверь → Твери
  if (lower.endsWith('ь')) return `${name.slice(0, -1)}и`
  // Химки → Химках, Мытищи → Мытищах: множественное число
  if (lower.endsWith('и')) return `${name.slice(0, -1)}ах`
  // Иваново → Иванове, Кемерово → Кемерове
  if (lower.endsWith('о')) return `${name.slice(0, -1)}е`
  // Сочи, Тбилиси и прочие несклоняемые оканчиваются на -и и уже обработаны;
  // остальное — согласная: Петербург → Петербурге, Ростов → Ростове
  if (/[бвгджзклмнпрстфхцчшщ]$/u.test(lower)) return `${name}е`

  return name
}
