/** Статус модерации отзыва */
export enum ReviewStatus {
  /** «Отзыв не подтверждён» — статус по умолчанию после отправки, ждёт модератора */
  Pending = 'pending',
  /** «Отзыв подтверждён» — модератор одобрил его в телеграм-боте */
  Confirmed = 'confirmed',
  /** Модератор отклонил: в публичных списках отзыва нет, автор видит причину */
  Rejected = 'rejected',
}
