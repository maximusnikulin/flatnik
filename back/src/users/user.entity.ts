import { Column, CreateDateColumn, Entity, Index, PrimaryGeneratedColumn } from 'typeorm'

/**
 * Пользователь; публично виден только никнейм.
 *
 * Опознаётся телефоном или почтой — тем, чем вошёл. Обязательного из них нет:
 * войти можно любым способом, поэтому оба nullable. Уникальность при этом
 * работает: Postgres считает NULL различными, и аккаунтов без телефона может
 * быть сколько угодно.
 */
@Entity('users')
export class User {
  @PrimaryGeneratedColumn('uuid')
  id!: string

  @Column({ type: 'text', unique: true, nullable: true })
  phone!: string | null

  /**
   * Подтверждённая почта в нижнем регистре: на неё уходит решение модератора.
   * Отдельного флага «подтверждена» нет — неподтверждённая сюда не попадает,
   * хранить её негде и незачем.
   *
   * Нижний регистр прямо в колонке, а не отдельной парой как у никнейма:
   * адрес показывается владельцу и только ему, поэтому исходное написание
   * сохранять не нужно.
   */
  @Column({ type: 'text', unique: true, nullable: true })
  email!: string | null

  /** Публичное имя: им подписаны отзывы. Регистр хранится как ввёл пользователь */
  @Column({ type: 'text' })
  nickname!: string

  /**
   * Тот же ник в нижнем регистре — на нём висит уникальность.
   * Отдельная колонка, а не уникальный индекс по lower(nickname): выражение
   * в индексе TypeORM не видит в метаданных сущности, и migration:generate
   * пытался бы его удалять при каждой генерации.
   */
  @Index({ unique: true })
  @Column({ type: 'text' })
  nicknameLower!: string

  /**
   * false — ник сгенерирован автоматически при создании аккаунта и пользователь
   * его ещё не выбирал. Ник обязателен всегда (отзыв должен быть чем-то подписан),
   * поэтому «не задан» выражается флагом, а не null.
   */
  @Column({ type: 'boolean', default: false })
  nicknameConfirmed!: boolean

  /**
   * Когда человек принял пользовательское соглашение и дал согласие на
   * обработку персональных данных; null — не принимал, и фронт показывает
   * ему блокирующее окно.
   *
   * Дата, а не флаг: согласие без момента получения ничего не доказывает,
   * а наружу всё равно уходит булев `consentAccepted`. Существующие
   * аккаунты получают null и проходят через окно при первом же заходе.
   */
  @Column({ type: 'timestamptz', nullable: true })
  consentAcceptedAt!: Date | null

  @CreateDateColumn()
  createdAt!: Date
}
