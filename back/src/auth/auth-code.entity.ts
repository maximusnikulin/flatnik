import { Column, CreateDateColumn, Entity, PrimaryColumn } from 'typeorm'

/**
 * Начатая попытка входа. Одна строка на номер: повторный запрос её перезаписывает,
 * успешный вход и просрочка — удаляют.
 *
 * В БД, а не в памяти процесса: деплой перезапускает контейнер, а в памяти это
 * обесценивало бы уже начатую (и оплаченную) авторизацию вместе с паузой между
 * запросами.
 *
 * Своего кода здесь нет и быть не может: в мобильной авторизации одноразовый код
 * выпускает и проверяет провайдер, нам он не известен.
 */
@Entity('auth_codes')
export class AuthCode {
  @PrimaryColumn({ type: 'text' })
  phone!: string

  /** Идентификатор заявки у провайдера; им адресуются mobile-id/status и /verify */
  @Column({ type: 'text' })
  requestId!: string

  /**
   * Последний известный статус заявки числом, как его отдаёт провайдер.
   * Хранится сырым: расшифровка живёт в одном месте — MobileIdStatus.
   */
  @Column({ type: 'int', default: 0 })
  providerStatus!: number

  /**
   * Провайдер прислал webhook о смене статуса — при следующем опросе спрашиваем
   * его, не дожидаясь паузы. Само тело webhook ничего не решает: оно приходит
   * без подписи, поэтому служит только поводом перепроверить.
   */
  @Column({ type: 'boolean', default: false })
  needsRecheck!: boolean

  /**
   * Секрет для опроса статуса, выдаётся фронту при запросе. Без него опрашивать
   * чужой номер мог бы кто угодно: подтверждение на SIM-карте вводом не
   * сопровождается, и невнимательно подтверждённый запрос отдал бы токен тому,
   * кто в этот момент опрашивает. Он же уходит в callbackUrl и аутентифицирует
   * webhook.
   */
  @Column({ type: 'text', default: '' })
  pollSecret!: string

  /** Когда последний раз спрашивали статус у провайдера — троттлинг опроса */
  @Column({ type: 'timestamptz', nullable: true })
  lastPollAt!: Date | null

  @Column({ type: 'timestamptz' })
  expiresAt!: Date

  /** Раньше этого момента новую попытку на номер не заводим: она стоит денег */
  @Column({ type: 'timestamptz' })
  nextRequestAt!: Date

  /** Неудачные попытки ввода кода; на пределе попытка гасится */
  @Column({ type: 'int', default: 0 })
  attempts!: number

  @CreateDateColumn()
  createdAt!: Date
}
